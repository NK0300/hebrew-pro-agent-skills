#!/usr/bin/env python3
"""Parse Hebrew-first skills and render per-tool files.

Source of truth is skills/<name>/SKILL.md. Tool files are derived.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass
from pathlib import Path

VERSION = "1.0.0"
BEGIN = "<!-- hebrew-pro-agent-skills:begin -->"
END = "<!-- hebrew-pro-agent-skills:end -->"
GENERATED_NOTE = (
    f"<!-- generated by hebrew-pro-agent-skills {VERSION}; do not edit by hand -->"
)

TOOLS = ("cursor", "claude", "copilot", "windsurf", "agents")
PROFILES = ("full", "web", "backend", "kids-hebrew")
ACTIVATIONS = ("always", "globs", "description")
CORE_NAME = "core-orchestrator"
CORE_MARKER = "Route by task. Do not load every skill."

REQUIRED_HEADINGS = (
    "## When to use",
    "## Rules",
    "## Examples",
    "## Checklist",
    "### Good",
    "### Bad",
)

NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
BRACE_RE = re.compile(r"\{([^{}]+)\}")


@dataclass(frozen=True)
class Skill:
    name: str
    description: str
    license: str
    body: str
    author: str
    version: str
    activation: str
    profiles: tuple[str, ...]
    order: str
    globs: str
    path: Path

    @property
    def profile_set(self) -> set[str]:
        return set(self.profiles)


@dataclass(frozen=True)
class PlannedFile:
    relpath: str
    content: str
    kind: str  # owned | managed


def repo_root_from(start: Path) -> Path:
    for candidate in [start, *start.parents]:
        if (candidate / "skills" / CORE_NAME / "SKILL.md").is_file():
            return candidate
    raise SystemExit(f"skills source not found from {start}")


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
        inner = value[1:-1]
        return inner.replace('\\"', '"').replace("\\n", "\n")
    return value


def parse_frontmatter(text: str, path: Path) -> tuple[dict[str, object], str]:
    if not text.startswith("---\n"):
        raise SystemExit(f"{path}: frontmatter must start at byte 0")
    end = text.find("\n---\n", 4)
    if end == -1:
        raise SystemExit(f"{path}: frontmatter is not closed")
    raw = text[4:end]
    body = text[end + 5 :]
    if body.startswith("\n"):
        body = body[1:]
    data: dict[str, object] = {}
    meta: dict[str, str] = {}
    mode = "top"
    folded_key: str | None = None
    folded: list[str] = []

    def finish_fold() -> None:
        nonlocal folded_key, folded
        if folded_key is None:
            return
        text_value = " ".join(part.strip() for part in folded if part.strip())
        if mode == "meta":
            meta[folded_key] = text_value
        else:
            data[folded_key] = text_value
        folded_key = None
        folded = []

    for line_no, line in enumerate(raw.splitlines(), start=2):
        if folded_key is not None:
            if line.startswith("  ") or line.strip() == "":
                folded.append(line.strip())
                continue
            finish_fold()
        if line.strip() == "":
            continue
        if line.startswith("metadata:"):
            if mode == "meta":
                raise SystemExit(f"{path}:{line_no}: nested metadata")
            mode = "meta"
            continue
        if mode == "meta":
            if not line.startswith("  ") or line.startswith("   "):
                raise SystemExit(f"{path}:{line_no}: metadata values use two spaces")
            key, sep, value = line.strip().partition(":")
            if not sep or not key:
                raise SystemExit(f"{path}:{line_no}: expected key: value")
            if value.strip() in {">", "|"}:
                folded_key = key
                folded = []
                continue
            meta[key] = _unquote(value)
            continue
        if line.startswith(" "):
            raise SystemExit(f"{path}:{line_no}: unexpected indent")
        key, sep, value = line.partition(":")
        if not sep or not key:
            raise SystemExit(f"{path}:{line_no}: expected key: value")
        if value.strip() in {">", "|"}:
            folded_key = key
            folded = []
            continue
        data[key] = _unquote(value)
    finish_fold()
    data["metadata"] = meta
    return data, body


def load_skill(path: Path) -> Skill:
    text = path.read_text(encoding="utf-8")
    data, body = parse_frontmatter(text, path)
    meta = data.get("metadata")
    if not isinstance(meta, dict):
        raise SystemExit(f"{path}: metadata block is required")
    name = str(data.get("name", ""))
    description = str(data.get("description", ""))
    profiles = tuple(
        part.strip() for part in str(meta.get("profiles", "")).split(",") if part.strip()
    )
    return Skill(
        name=name,
        description=description,
        license=str(data.get("license", "")),
        body=body.strip() + "\n",
        author=str(meta.get("author", "")),
        version=str(meta.get("version", "")),
        activation=str(meta.get("activation", "")),
        profiles=profiles,
        order=str(meta.get("order", "")),
        globs=str(meta.get("globs", "")),
        path=path,
    )


def load_skills(root: Path) -> list[Skill]:
    skills_dir = root / "skills"
    found = sorted(skills_dir.glob("*/SKILL.md"))
    if not found:
        raise SystemExit(f"no skills under {skills_dir}")
    skills = [load_skill(path) for path in found]
    skills.sort(key=lambda skill: skill.order)
    return skills


def split_globs(value: str) -> list[str]:
    parts: list[str] = []
    buf: list[str] = []
    depth = 0
    for char in value:
        if char == "{":
            depth += 1
        elif char == "}":
            depth = max(0, depth - 1)
        if char == "," and depth == 0:
            item = "".join(buf).strip()
            if item:
                parts.append(item)
            buf = []
            continue
        buf.append(char)
    tail = "".join(buf).strip()
    if tail:
        parts.append(tail)
    return parts


def expand_one(pattern: str) -> list[str]:
    match = BRACE_RE.search(pattern)
    if match is None:
        return [pattern]
    expanded: list[str] = []
    for option in match.group(1).split(","):
        expanded.extend(
            expand_one(pattern[: match.start()] + option.strip() + pattern[match.end() :])
        )
    return expanded


def flat_globs(value: str) -> str:
    seen: list[str] = []
    for part in split_globs(value):
        for item in expand_one(part):
            if item not in seen:
                seen.append(item)
    return ",".join(seen)


def yaml_quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def select_skills(skills: list[Skill], profile: str) -> list[Skill]:
    if profile not in PROFILES:
        raise SystemExit(f"unknown profile: {profile}")
    if profile == "full":
        chosen = list(skills)
    else:
        chosen = [skill for skill in skills if profile in skill.profile_set]
    if not any(skill.name == CORE_NAME for skill in chosen):
        raise SystemExit(f"profile {profile} is missing {CORE_NAME}")
    return chosen


def parse_tools(value: str) -> list[str]:
    tools = [part.strip() for part in value.split(",") if part.strip()]
    if not tools:
        raise SystemExit("--tools must list at least one tool")
    unknown = [tool for tool in tools if tool not in TOOLS]
    if unknown:
        raise SystemExit(f"unknown tool: {', '.join(unknown)}")
    # Stable order, drop duplicates.
    return [tool for tool in TOOLS if tool in set(tools)]


def core_flags(mode: str, tools: set[str], dedupe: bool) -> dict[str, object]:
    """Decide where the always-on contract is injected.

    Project installs avoid handing Cursor, Copilot, or Windsurf two full copies.
    Cursor reads root AGENTS.md and root CLAUDE.md as always-on. Devin reads
    AGENTS.md and .cursor/rules. Claude Code does not read AGENTS.md, so a
    Claude install either embeds the contract or imports AGENTS.md.
    Global files live in different products, so each selected tool gets a full
    copy, except Devin, which also reads ~/.claude/CLAUDE.md.
    """

    if mode not in {"project", "global"}:
        raise SystemExit(f"unknown mode: {mode}")
    if not dedupe:
        return {
            "cursor_always": "cursor" in tools,
            "windsurf_always": "windsurf" in tools,
            "claude_body": "full" if "claude" in tools else None,
            "agents_body": "full" if "agents" in tools else None,
            "gemini_body": "full" if "agents" in tools else None,
            "copilot_body": "full" if "copilot" in tools else None,
        }
    if mode == "global":
        return {
            "cursor_always": "cursor" in tools,
            "windsurf_always": "windsurf" in tools and "claude" not in tools,
            "claude_body": "full" if "claude" in tools else None,
            "agents_body": "full" if "agents" in tools else None,
            "gemini_body": "full" if "agents" in tools else None,
            "copilot_body": "full" if "copilot" in tools else None,
        }
    agents = "agents" in tools
    claude = "claude" in tools
    return {
        "cursor_always": "cursor" in tools and not (agents or claude),
        "windsurf_always": "windsurf" in tools and not (agents or "cursor" in tools),
        "claude_body": ("pointer" if agents else "full") if claude else None,
        "agents_body": "full" if agents else None,
        "gemini_body": "pointer" if agents else None,
        "copilot_body": ("pointer" if agents else "full") if "copilot" in tools else None,
    }


def pointer_body(target: str) -> str:
    return (
        "# Hebrew-first skills\n\n"
        "Talk to the user in Hebrew. Write code, comments, and commits in English. "
        "Write product copy in natural Hebrew.\n\n"
        f"@{target}\n\n"
        f"The router and the rest of the contract are in `{target}`. "
        "Follow that file. Do not copy it into this one.\n"
    )


def managed_block(body: str, profile: str) -> str:
    return (
        f"{BEGIN}\n"
        f"<!-- version: {VERSION} profile: {profile} -->\n"
        "<!-- Managed by hebrew-pro-agent-skills. Re-run install.sh to update. -->\n\n"
        f"{body.rstrip()}\n"
        f"{END}\n"
    )


def _with_note(frontmatter: str, body: str) -> str:
    return f"{frontmatter}\n{GENERATED_NOTE}\n\n{body.rstrip()}\n"


def render_cursor(skill: Skill, always: bool) -> str:
    lines = ["---", f"description: {yaml_quote(skill.description)}"]
    if skill.activation == "globs" and skill.globs and not always:
        lines.append(f"globs: {yaml_quote(flat_globs(skill.globs))}")
    lines.append(f"alwaysApply: {'true' if always else 'false'}")
    lines.append("---")
    return _with_note("\n".join(lines), skill.body)


def render_claude(skill: Skill) -> str:
    lines = [
        "---",
        f"name: {skill.name}",
        f"description: {yaml_quote(skill.description)}",
        "license: MIT",
    ]
    if skill.name == CORE_NAME:
        lines.append("disable-model-invocation: true")
    lines.append("---")
    return _with_note("\n".join(lines), skill.body)


def render_copilot_instruction(skill: Skill) -> str:
    if not skill.globs:
        raise SystemExit(f"{skill.name}: copilot applyTo needs metadata.globs")
    lines = [
        "---",
        f"applyTo: {yaml_quote(flat_globs(skill.globs))}",
        f"description: {yaml_quote(skill.description)}",
        "---",
    ]
    return _with_note("\n".join(lines), skill.body)


def render_windsurf(skill: Skill, always: bool) -> str:
    if always:
        trigger = "always_on"
    elif skill.activation == "globs":
        trigger = "glob"
    else:
        trigger = "model_decision"
    lines = ["---", f"trigger: {trigger}", f"description: {yaml_quote(skill.description)}"]
    if trigger == "glob":
        lines.append(f"globs: {yaml_quote(flat_globs(skill.globs))}")
    lines.append("---")
    return _with_note("\n".join(lines), skill.body)


def build_plan(
    root: Path,
    profile: str,
    tools: list[str],
    mode: str,
    dedupe: bool = True,
) -> list[PlannedFile]:
    skills = select_skills(load_skills(root), profile)
    toolset = set(tools)
    flags = core_flags(mode, toolset, dedupe)
    core = next(skill for skill in skills if skill.name == CORE_NAME)
    planned: list[PlannedFile] = []

    def add(relpath: str, content: str, kind: str) -> None:
        planned.append(PlannedFile(relpath=relpath, content=content, kind=kind))

    if "cursor" in toolset:
        for skill in skills:
            always = skill.name == CORE_NAME
            if always and not flags["cursor_always"]:
                continue
            add(
                f".cursor/rules/{skill.name}.mdc",
                render_cursor(skill, always=always),
                "owned",
            )
    if "claude" in toolset:
        for skill in skills:
            add(
                f".claude/skills/{skill.name}/SKILL.md",
                render_claude(skill),
                "owned",
            )
        if flags["claude_body"] == "full":
            claude_body = core.body
        elif flags["claude_body"] == "pointer":
            claude_body = pointer_body("AGENTS.md")
        else:
            claude_body = ""
        if claude_body:
            add("CLAUDE.md", managed_block(claude_body, profile), "managed")
    if "copilot" in toolset:
        for skill in skills:
            if skill.name == CORE_NAME:
                continue
            add(
                f".github/instructions/{skill.name}.instructions.md",
                render_copilot_instruction(skill),
                "owned",
            )
        if flags["copilot_body"] == "full":
            copilot_body = core.body
        elif flags["copilot_body"] == "pointer":
            copilot_body = pointer_body("AGENTS.md")
        else:
            copilot_body = ""
        if copilot_body:
            add(
                ".github/copilot-instructions.md",
                managed_block(copilot_body, profile),
                "managed",
            )
    if "windsurf" in toolset:
        for skill in skills:
            always = skill.name == CORE_NAME
            if always and not flags["windsurf_always"]:
                continue
            rendered = render_windsurf(skill, always=always)
            add(f".windsurf/rules/{skill.name}.md", rendered, "owned")
            add(f".devin/rules/{skill.name}.md", rendered, "owned")
    if "agents" in toolset:
        if flags["agents_body"] == "full":
            add("AGENTS.md", managed_block(core.body, profile), "managed")
        gemini_flag = flags["gemini_body"]
        if gemini_flag == "full":
            gemini_body = core.body
        elif gemini_flag == "pointer":
            gemini_body = pointer_body("AGENTS.md")
        else:
            gemini_body = ""
        if gemini_body:
            add("GEMINI.md", managed_block(gemini_body, profile), "managed")

    if any(skill.name == "ui-rtl-system" for skill in skills):
        template = (root / "skills" / "ui-rtl-system" / "tokens.template.css").read_text(
            encoding="utf-8"
        )
        stamped = (
            f"/* generated by hebrew-pro-agent-skills {VERSION}; do not edit by hand */\n"
            + template
        )
        if not stamped.endswith("\n"):
            stamped += "\n"
        add(".hebrew-skills/templates/tokens.template.css", stamped, "owned")
        if "claude" in toolset:
            add(".claude/skills/ui-rtl-system/tokens.template.css", stamped, "owned")
    return planned


def destination(mode: str, home: Path, target: Path, relpath: str) -> Path | None:
    """Map a project-relative plan path to the file we actually write."""

    if mode == "project":
        return target / relpath
    if mode != "global":
        raise SystemExit(f"unknown mode: {mode}")
    mapping = {
        ".cursor/": home / ".cursor",
        ".claude/": home / ".claude",
        ".github/instructions/": home / ".copilot" / "instructions",
        ".windsurf/rules/": home / ".devin" / "rules",
        ".hebrew-skills/": home / ".hebrew-pro-agent-skills",
    }
    for prefix, dest_root in mapping.items():
        if relpath.startswith(prefix):
            return dest_root / relpath[len(prefix) :]
    singles = {
        ".github/copilot-instructions.md": home / ".copilot" / "copilot-instructions.md",
        "CLAUDE.md": home / ".claude" / "CLAUDE.md",
        "AGENTS.md": home / ".codex" / "AGENTS.md",
        "GEMINI.md": home / ".gemini" / "GEMINI.md",
        # Project Devin rules duplicate Windsurf rules. Globally one tree is enough.
        # Returning None for .devin/rules happens below via startswith miss... 
    }
    if relpath in singles:
        return singles[relpath]
    if relpath.startswith(".devin/"):
        return None
    raise SystemExit(f"no global destination for {relpath}")


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def merge_managed(existing: str | None, block: str) -> str:
    block = block if block.endswith("\n") else block + "\n"
    if existing is None or existing == "":
        return block
    begin_count = existing.count(BEGIN)
    end_count = existing.count(END)
    if begin_count == 0 and end_count == 0:
        base = existing if existing.endswith("\n") else existing + "\n"
        if not base.endswith("\n\n"):
            base += "\n"
        return base + block
    if begin_count != 1 or end_count != 1:
        raise SystemExit(
            "managed block markers are missing or duplicated; refusing to overwrite the file"
        )
    start = existing.index(BEGIN)
    end = existing.index(END)
    if end < start:
        raise SystemExit("managed block markers are out of order; refusing to overwrite")
    merged = existing[:start] + block.rstrip("\n") + existing[end + len(END) :]
    if not merged.endswith("\n"):
        merged += "\n"
    return merged


def remove_managed(existing: str) -> str:
    begin_count = existing.count(BEGIN)
    end_count = existing.count(END)
    if begin_count == 0 and end_count == 0:
        return existing
    if begin_count != 1 or end_count != 1:
        raise SystemExit(
            "managed block markers are missing or duplicated; refusing to edit the file"
        )
    start = existing.index(BEGIN)
    end = existing.index(END) + len(END)
    if existing.index(END) < start:
        raise SystemExit("managed block markers are out of order; refusing to edit")
    merged = existing[:start] + existing[end:]
    merged = re.sub(r"\n{3,}", "\n\n", merged)
    if merged.strip() == "":
        return ""
    if not merged.endswith("\n"):
        merged += "\n"
    return merged
